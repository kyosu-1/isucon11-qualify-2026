#!/usr/bin/env bash
# isuenv が振ったホストの private IP を hosts.generated.mk に書き出す（環境を作り直すたびに変わる）。
set -euo pipefail
ssh() { command ssh -o LogLevel=ERROR -o ConnectTimeout=10 "$@"; }
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "# Generated by tools/gen-hosts.sh. DO NOT EDIT. $(date '+%F %T')"
  for h in $(awk '/^Host isucon11-qualify-/ {print $2}' ~/.ssh/isuenv_config); do
    n="${h##*-}"; ip=$(ssh "$h" 'hostname -I | awk "{print \$1}"')
    if [ "$n" -le 3 ]; then echo "ISU${n}_IP := $ip"; else echo "BENCH := $h"; echo "BENCH_IP := $ip"; fi
  done
} > "$ROOT/hosts.generated.mk"
cat "$ROOT/hosts.generated.mk"
